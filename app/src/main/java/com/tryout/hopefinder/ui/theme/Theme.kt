/**
 * Hope-Finder Professional Theme
 * Material Design 3 implementation optimized for emergency rescue operations
 * 
 * Features:
 * - Professional color scheme for mission-critical applications
 * - High-contrast accessibility support
 * - Dark theme for eye comfort during extended use
 * - Comprehensive typography hierarchy
 * - Consistent spacing and elevation system
 */
@Composable
fun HopeFinderTheme(
    content: @Composable () -> Unit
) {
    MaterialTheme(
        colorScheme = HopeFinderColorScheme,
        typography = HopeFinderTypography,
        shapes = HopeFinderShapes,
        content = content
    )
}

